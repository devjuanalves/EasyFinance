import { useState } from 'react';
import { useWorkspace } from '../../finance/WorkspaceContext.js';
import { blankInvoice } from '../incomeService.js';
import { Field } from './IncomeUI.jsx';
import InvoiceItems from './InvoiceItems.jsx';
export default function RecurringTemplateForm({ client, onSaved }) {
  const { ledger, filters, command } = useWorkspace();
  const [form, setForm] = useState(() => ({
    ...blankInvoice(ledger.data, filters, client.id),
    name: '',
    frequency: 'monthly',
    nextDate: ledger.data.asOf,
  }));
  const [error, setError] = useState('');
  return (
    <form
      className="income-form"
      noValidate
      onSubmit={(e) => {
        e.preventDefault();
        try {
          command('saveTemplate', { template: form });
          onSaved();
        } catch (e) {
          setError(e.message);
        }
      }}
    >
      <p>
        Prepare reviewable drafts manually. No scheduled job, revenue, or email
        is generated by saving a template.
      </p>
      {error && <p role="alert">{error}</p>}
      <div className="form-grid">
        <Field
          label="Template Name"
          value={form.name}
          onChange={(e) => setForm({ ...form, name: e.target.value })}
        />
        <Field label="Template Client" value={client.name} readOnly />
        <Field label="Frequency">
          <select
            aria-label="Frequency"
            value={form.frequency}
            onChange={(e) => setForm({ ...form, frequency: e.target.value })}
          >
            <option value="monthly">Monthly (30-day demo cycle)</option>
            <option value="weekly">Weekly</option>
            <option value="quarterly">Quarterly (90-day demo cycle)</option>
          </select>
        </Field>
        <Field
          label="Next Preparation Date"
          type="date"
          value={form.nextDate}
          onChange={(e) => setForm({ ...form, nextDate: e.target.value })}
        />
        <Field
          label="Template Payment Terms"
          inputMode="numeric"
          value={form.paymentTerms}
          onChange={(e) => setForm({ ...form, paymentTerms: e.target.value })}
        />
        <Field label="Template Currency" value={form.currency} readOnly />
      </div>
      <InvoiceItems
        items={form.items}
        currency={form.currency}
        onChange={(items) => setForm({ ...form, items })}
      />
      <button className="primary-button">Save Review Template</button>
    </form>
  );
}
